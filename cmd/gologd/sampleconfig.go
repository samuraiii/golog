// sampleConfigCommand implements "gologd sample-config [-o file] [-f]": it prints
// the sample configuration, or writes it to a file (refusing to overwrite one
// unless -f is given). It returns the process exit status.
func sampleConfigCommand(argv []string, stdout io.Writer) int {
	fs := flag.NewFlagSet("sample-config", flag.ContinueOnError)
	out := fs.String("o", "", "write the configuration to this file instead of standard output")
	force := fs.Bool("f", false, "overwrite an existing file")
	fs.SetOutput(os.Stderr)
	if err := fs.Parse(argv); err != nil {
		return 2
	}
	text, err := renderSampleConfig()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gologd:", err)
		return 1
	}
	if "" == *out || "-" == *out {
		fmt.Fprint(stdout, text)
		return 0
	}
	flags := os.O_WRONLY | os.O_CREATE | os.O_EXCL
	if *force {
		flags = os.O_WRONLY | os.O_CREATE | os.O_TRUNC
	}
	if dir := filepath.Dir(*out); "." != dir {
		_ = os.MkdirAll(dir, 0o750)
	}
	f, err := os.OpenFile(*out, flags, 0o640)
	if err != nil {
		if errors.Is(err, os.ErrExist) {
			fmt.Fprintf(os.Stderr, "gologd: %s exists; use -f to overwrite it\n", *out)
		} else {
			fmt.Fprintln(os.Stderr, "gologd:", err)
		}
		return 1
	}
	defer f.Close()
	if _, err := io.WriteString(f, text); err != nil {
		fmt.Fprintln(os.Stderr, "gologd:", err)
		return 1
	}
	fmt.Fprintf(os.Stderr, "wrote %s; start with: gologd -c %s\n", *out, *out)
	return 0
}
