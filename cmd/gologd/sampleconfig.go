// renderSampleConfig returns sampleConfig with a freshly generated random
// salt (160 bits from crypto/rand) in the commented-out Salt line.
func renderSampleConfig() (string, error) {
	raw := make([]byte, 20)
	if _, err := rand.Read(raw); err != nil {
		return "", err
	}
	salt := strings.ToLower(base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString(raw))
	return strings.Replace(sampleConfig, "@@SALT@@", salt, 1), nil
}

